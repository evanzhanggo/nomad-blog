import { readFileSync, writeFileSync } from "node:fs";
import { Resvg } from "@resvg/resvg-js";

const fontFiles = [
  "/usr/share/fonts/truetype/noto/NotoSans-Regular.ttf",
  "/usr/share/fonts/truetype/droid/DroidSansFallbackFull.ttf",
];
const root = new URL("../", import.meta.url);

function render(svgPath, width) {
  const svg = readFileSync(new URL(svgPath, root));
  const resvg = new Resvg(svg, {
    fitTo: { mode: "width", value: width },
    font: {
      fontFiles,
      defaultFontFamily: "Noto Sans",
      loadSystemFonts: false,
    },
  });
  return resvg.render().asPng();
}

function pngToIco(png, size) {
  const header = Buffer.alloc(22);
  header.writeUInt16LE(0, 0);
  header.writeUInt16LE(1, 2);
  header.writeUInt16LE(1, 4);
  header.writeUInt8(size >= 256 ? 0 : size, 6);
  header.writeUInt8(size >= 256 ? 0 : size, 7);
  header.writeUInt16LE(1, 10);
  header.writeUInt16LE(32, 12);
  header.writeUInt32LE(png.length, 14);
  header.writeUInt32LE(22, 18);
  return Buffer.concat([header, png]);
}

const icon512 = render("assets/brand/favicon.svg", 512);
const apple = render("assets/brand/favicon.svg", 180);
const icon32 = render("assets/brand/favicon.svg", 32);
const og = render("assets/brand/og.svg", 1200);
const ico = pngToIco(icon32, 32);
const svg = readFileSync(new URL("assets/brand/favicon.svg", root), "utf8");

writeFileSync(new URL("assets/brand/icon-512.png", root), icon512);
writeFileSync(new URL("assets/brand/apple-touch-icon.png", root), apple);
writeFileSync(new URL("assets/brand/og.png", root), og);
writeFileSync(new URL("assets/brand/favicon.ico", root), ico);

const source = `// Generated by scripts/render-icons.mjs. Do not edit by hand.
export const FAVICON_SVG = ${JSON.stringify(svg)};

export const ICON_512_PNG = ${JSON.stringify(icon512.toString("base64"))};
export const APPLE_TOUCH_PNG = ${JSON.stringify(apple.toString("base64"))};
export const OG_PNG = ${JSON.stringify(og.toString("base64"))};
export const FAVICON_ICO = ${JSON.stringify(ico.toString("base64"))};

export function decodeAsset(base64: string): Uint8Array {
  const binary = atob(base64);
  const bytes = new Uint8Array(binary.length);
  for (let index = 0; index < binary.length; index++) bytes[index] = binary.charCodeAt(index);
  return bytes;
}
`;
writeFileSync(new URL("src/brand-assets.ts", root), source);
console.log(
  `icon-512 ${icon512.length} apple ${apple.length} og ${og.length} ico ${ico.length}`,
);
